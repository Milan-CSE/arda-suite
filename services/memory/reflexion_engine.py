#!/usr/bin/env python3
"""Reflexion Engine — converts verified failure->fix cycles into durable gotchas.

Grounding:
  Inspired by "Reflexion: Language Agents with Verbal Reinforcement Learning" (arXiv:2303.11366)
  and A-MEM (arXiv:2502.12110).

Reads unprocessed records from verified-failures.jsonl (generated by lessons_detect.py),
synthesizes a concrete engineering gotcha using the local LLM (or a deterministic fallback
if Ollama is down), and stores it into mem0 under agent_id="reflexion" and verbatim=True.
"""

import argparse
import datetime
import json
import os
import sys
import urllib.error
import urllib.request

MEM0_ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, MEM0_ROOT)

import config
from config import get_memory

VERIFIED_LOG = os.path.join(MEM0_ROOT, "verified-failures.jsonl")
OLLAMA_URL = "http://localhost:11434/api/generate"
OWNER = os.environ.get("MEM0_OWNER", "default")


def load_verified():
    """Load all records from verified-failures.jsonl."""
    if not os.path.exists(VERIFIED_LOG):
        return []
    records = []
    with open(VERIFIED_LOG, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except Exception:
                continue
    return records


def write_verified(records):
    """Rewrite verified-failures.jsonl atomically."""
    tmp = VERIFIED_LOG + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    os.replace(tmp, VERIFIED_LOG)


def query_ollama_reflexion(command, edited_files, project):
    """Ask configured LLM (external API or local Ollama) to distill failure-fix into a concise gotcha."""
    files_str = ", ".join(edited_files)
    prompt = (
        f"You are an expert developer creating a short, high-value gotcha lesson from a test failure that was fixed.\n"
        f"Project: {project or 'general'}\n"
        f"Test/Build Command: {command}\n"
        f"Files changed to resolve the failure: {files_str}\n\n"
        f"State in ONE short, specific, actionable sentence (under 140 chars) the gotcha or fix rule.\n"
        f"Only return the single sentence, no commentary or quotes."
    )

    active_cfg = config.get_config()
    llm_info = active_cfg.get("llm", {})
    provider = llm_info.get("provider", "ollama")
    cfg = llm_info.get("config", {})

    if provider == "openai":
        try:
            from openai import OpenAI
            client = OpenAI(api_key=cfg.get("api_key") or "none", base_url=cfg.get("openai_base_url"))
            resp = client.chat.completions.create(
                model=cfg.get("model", config.LLM_MODEL),
                messages=[{"role": "user", "content": prompt}],
                temperature=0.1,
                max_tokens=100,
                timeout=10,
            )
            out = (resp.choices[0].message.content or "").strip().strip('"').strip("'")
            if out and len(out) > 10:
                return out
        except Exception:
            pass
    else:
        ollama_base = cfg.get("ollama_base_url", "http://localhost:11434")
        ollama_url = f"{ollama_base.rstrip('/')}/api/generate"
        req_body = {
            "model": cfg.get("model", config.LLM_MODEL),
            "prompt": prompt,
            "stream": False,
            "options": {"temperature": 0.1, "num_predict": 100},
        }
        try:
            req = urllib.request.Request(
                ollama_url,
                data=json.dumps(req_body).encode("utf-8"),
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=8) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                out = data.get("response", "").strip().strip('"').strip("'")
                if out and len(out) > 10:
                    return out
        except Exception:
            pass

    # Deterministic fallback when LLM is offline or slow
    return f"Resolved failing `{command}` by fixing: {files_str}"


def process_record(record, dry_run=False, mem_instance=None):
    """Process a single verified failure record into a stored reflection."""
    cmd = record.get("command", "")
    files = record.get("edited_files", [])
    project = record.get("project") or "personal"

    lesson = query_ollama_reflexion(cmd, files, project)
    formatted_lesson = f"[GOTCHA] {lesson}"

    if not dry_run:
        mem = mem_instance or get_memory()
        mem.add(
            formatted_lesson,
            user_id=OWNER,
            run_id=project,
            agent_id="reflexion",
            metadata={"status": "active", "source": "reflexion", "command": cmd},
            infer=False,  # verbatim: already distilled
        )
    return formatted_lesson


def run_reflexion(dry_run=False):
    """Scan and process all pending verified failure records."""
    records = load_verified()
    unprocessed = [r for r in records if not r.get("processed")]
    if not unprocessed:
        return []

    mem = None if dry_run else get_memory()
    results = []

    for r in unprocessed:
        lesson = process_record(r, dry_run=dry_run, mem_instance=mem)
        r["processed"] = True
        r["processed_at"] = datetime.datetime.now(datetime.timezone.utc).isoformat()
        r["lesson"] = lesson
        results.append(lesson)

    if not dry_run:
        write_verified(records)

    return results


def main():
    ap = argparse.ArgumentParser(description="Process verified failures into stored memories")
    ap.add_argument("--dry-run", action="store_true", help="Print lessons without saving to memory")
    args = ap.parse_args()

    results = run_reflexion(dry_run=args.dry_run)
    print(f"Reflexion: processed {len(results)} new failure->fix cycles.")
    for res in results:
        print(f"  -> {res}")


if __name__ == "__main__":
    main()
